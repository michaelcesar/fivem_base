// Server: preview thumbnails for clothing components/props, served by the standalone
// `lite_clothingimages` resource - one PNG per (component-or-prop id, gender, drawable), matching
// exactly how the source pack itself was organized. Filenames are built here, not looked up in a
// generated table (unlike `lite_vehicleimages`'s `VehicleImages`, which exists to avoid a 404
// placeholder in a component with no `onError` handling) - `Input.tsx` already hides the image on
// error, so a missing file just means no thumbnail rather than a broken one. See ADR-078.
//
// Coverage: components 1 (mask), 3 (torso/arms), 4 (legs), 5 (bags), 6 (shoes), 7 (accessory),
// 8 (undershirt), 9 (armor), 11 (torso2/tops); props 0 (hat), 1 (glasses), 2 (ear), 6 (watch),
// 7 (bracelet). Component 10 (decals) has no images - the source pack never had any.
//
// Only freemode peds (`mp_m_freemode_01`/`mp_f_freemode_01`) are covered - a custom ped's
// components use an entirely different mesh, so a freemode preview would be actively misleading
// rather than merely missing. Callers must gate on `isPedFreemodeModel` themselves.
const COMPONENTS_WITH_IMAGES = new Set([1, 3, 4, 5, 6, 7, 8, 9, 11]);
const PROPS_WITH_IMAGES = new Set([0, 1, 2, 6, 7]);

function buildUrl(prefix: string, id: number, isPedMale: boolean, drawable: number): string {
  const gender = isPedMale ? 'm' : 'f';
  return `nui://lite_clothingimages/images/${prefix}${id}_${gender}_${drawable}.png`;
}

export function clothingComponentImage(
  componentId: number,
  isPedFreemodeModel: boolean | undefined,
  isPedMale: boolean | undefined,
  drawable: number,
): string | undefined {
  if (!isPedFreemodeModel || isPedMale === undefined || !COMPONENTS_WITH_IMAGES.has(componentId)) return undefined;
  return buildUrl('c', componentId, isPedMale, drawable);
}

export function clothingPropImage(
  propId: number,
  isPedFreemodeModel: boolean | undefined,
  isPedMale: boolean | undefined,
  drawable: number,
): string | undefined {
  if (!isPedFreemodeModel || isPedMale === undefined || !PROPS_WITH_IMAGES.has(propId)) return undefined;
  return buildUrl('p', propId, isPedMale, drawable);
}

// Server: which drawables `lite_clothingimages` actually has a picture for, per component/prop
// and gender - generated by `generate/manifest.js` from what is really in `images/`, not guessed
// from the theoretical 0-255 range. `DrawableGrid.tsx` uses this to render a grid of exactly the
// real items, instead of 256 tiles per category with most of them 404ing. See ADR-078.
type ClothingManifest = Record<string, { m: number[]; f: number[] }>;

let manifestPromise: Promise<ClothingManifest> | undefined;

function fetchClothingManifest(): Promise<ClothingManifest> {
  if (!manifestPromise) {
    manifestPromise = fetch('nui://lite_clothingimages/manifest.json')
      .then(res => res.json())
      .catch(() => ({} as ClothingManifest));
  }
  return manifestPromise;
}

async function drawablesFor(key: string, isPedMale: boolean | undefined): Promise<number[]> {
  if (isPedMale === undefined) return [];
  const manifest = await fetchClothingManifest();
  return manifest[key]?.[isPedMale ? 'm' : 'f'] ?? [];
}

export function componentDrawables(componentId: number, isPedMale: boolean | undefined): Promise<number[]> {
  return drawablesFor(`c${componentId}`, isPedMale);
}

export function propDrawables(propId: number, isPedMale: boolean | undefined): Promise<number[]> {
  return drawablesFor(`p${propId}`, isPedMale);
}
